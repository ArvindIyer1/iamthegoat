import math

board = [' '] * 9

def print_board():
    for i in range(0, 9, 3):
        print(board[i], "|", board[i+1], "|", board[i+2])
        if i < 6:
            print("--|---|--")

def check_winner(player):
    wins = [
        [0,1,2], [3,4,5], [6,7,8],
        [0,3,6], [1,4,7], [2,5,8],
        [0,4,8], [2,4,6]
    ]

    for pos in wins:
        if all(board[i] == player for i in pos):
            return True
    return False

def is_draw():
    return ' ' not in board

